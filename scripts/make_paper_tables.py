"""Paper tables with explicit selection rules (scripts/make_tables.py pools every CSV, which mixes steps,
sweep modes and old runs). Writes paper/tables/{format_study,all18,sweeps}.tex and results/paper_tables.md.

Selection:
  format study  results/*policy_only_fs_mse_<format>[_seedN]_20000_<Task>.csv (final checkpoint, perfect
                commands, no sweep mode); seeds pooled per format; Wilson 95% interval on the pooled count.
  18 tasks      results/*policy_only_fs_mse_sentence_all18_<step>_<Task>.csv, mean over tasks per step.
  sweeps        results/*policy_only_fs_mse_<run>_20000_<mode>_<Task>.csv, pooled over seeds per format and mode.
    python scripts/make_paper_tables.py
"""
from __future__ import annotations

import collections
import csv
import glob
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASKS = ["OpenDrawer", "PickPlaceCounterToCabinet", "TurnOnMicrowave"]
SHORT = {"OpenDrawer": "Drawer", "PickPlaceCounterToCabinet": "Pick-place", "TurnOnMicrowave": "Microwave"}
FORMATS = ["sentence", "kv_text", "points_2d", "points_3d_rgb", "points_3d", "pose_path"]
MODES = ["err0cm", "err1cm", "err2cm", "err5cm", "err10cm", "err20cm", "err40cm", "distractor", "distractor10pct", "distractor30pct", "drop_point", "drop_name",
         "drop_source", "rename_thing"]


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def count(f):
    r = list(csv.DictReader(open(f)))
    return sum(int(x["success"]) for x in r), len(r)


def cell(k, n):
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.0f} [{100 * lo:.0f}, {100 * hi:.0f}] (n={n})" if n else "-"


def main():
    res = ROOT / "results"
    fmt = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    seeds = collections.defaultdict(set)
    sweep = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    all18 = collections.defaultdict(dict)
    pat_main = re.compile(r"policy_only_fs_mse_(\w+?)(_seed\d)?_20000_(" + "|".join(TASKS) + r")\.csv$")
    pat_sweep = re.compile(r"policy_only_fs_mse_(\w+?)(_seed\d)?_20000_(" + "|".join(MODES) + r")_(" + "|".join(TASKS) + r")\.csv$")
    pat_18 = re.compile(r"policy_only_fs_mse_sentence_all18_(\d+)_(\w+)\.csv$")
    for f in sorted(glob.glob(str(res / "*.csv"))):
        name = Path(f).name
        m = pat_sweep.search(name)
        if m:
            run, seed, mode, task = m.groups()
            if run in FORMATS:
                k, n = count(f)
                sweep[(run, mode)][task][0] += k
                sweep[(run, mode)][task][1] += n
            continue
        m = pat_main.search(name)
        if m:
            run, seed, task = m.groups()
            if run in FORMATS:
                k, n = count(f)
                fmt[run][task][0] += k
                fmt[run][task][1] += n
                seeds[run].add(seed or "_seed0")
            continue
        m = pat_18.search(name)
        if m:
            step, task = m.groups()
            all18[int(step)][task] = count(f)
    md = ["# Paper tables", "", "Generated by `scripts/make_paper_tables.py`. Success % [Wilson 95% CI] (episodes).", ""]
    tex = {}
    # format study
    md += ["## Format study (3 smoke tasks, regression, 20k steps, perfect commands)", "",
           "| Format | Seeds | " + " | ".join(SHORT[t] for t in TASKS) + " |", "|---|---|---|---|---|"]
    rows = []
    for f_ in FORMATS:
        if f_ not in fmt:
            continue
        c = [cell(*fmt[f_][t]) for t in TASKS]
        md.append(f"| {f_} | {len(seeds[f_])} | " + " | ".join(c) + " |")
        rows.append(f"{f_.replace('_', chr(92) + '_')} & {len(seeds[f_])} & " + " & ".join(
            f"{100 * fmt[f_][t][0] / max(1, fmt[f_][t][1]):.0f}" for t in TASKS) + r" \\")
    tex["format_study"] = ("\\begin{tabular}{lcccc}\n\\toprule\nFormat & Seeds & Drawer & Pick-place & Microwave \\\\\n"
                           "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    # 18 tasks
    md += ["", "## Stock sentence format on 18 tasks (regression, one seed)", "", "| Step | Tasks | Mean success |", "|---|---|---|"]
    rows = []
    for st in sorted(all18):
        k = sum(v[0] for v in all18[st].values())
        n = sum(v[1] for v in all18[st].values())
        md.append(f"| {st} | {len(all18[st])} | {cell(k, n)} |")
        rows.append(f"{st // 1000}k & {len(all18[st])} & {100 * k / n:.1f} \\\\")
    tex["all18"] = ("\\begin{tabular}{rcc}\n\\toprule\nStep & Tasks & Mean success (\\%) \\\\\n\\midrule\n"
                    + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    if all18:
        last = max(all18)
        md += ["", f"Per task at {last}:", "", "| Task | Success |", "|---|---|"]
        for t, (k, n) in sorted(all18[last].items(), key=lambda x: -x[1][0] / x[1][1]):
            md.append(f"| {t} | {cell(k, n)} |")
    # sweeps
    md += ["", "## Part N sweeps (final checkpoints, seeds pooled)", "",
           "| Format | Mode | " + " | ".join(SHORT[t] for t in TASKS) + " |", "|---|---|---|---|---|"]
    rows = []
    for f_ in FORMATS:
        for mode in MODES:
            if (f_, mode) not in sweep:
                continue
            d = sweep[(f_, mode)]
            md.append(f"| {f_} | {mode} | " + " | ".join(cell(*d[t]) if t in d else "-" for t in TASKS) + " |")
            rows.append(f"{f_.replace('_', chr(92) + '_')} & {mode.replace('_', chr(92) + '_')} & " + " & ".join(
                f"{100 * d[t][0] / max(1, d[t][1]):.0f}" if t in d else "-" for t in TASKS) + r" \\")
    tex["sweeps"] = ("\\begin{tabular}{llccc}\n\\toprule\nFormat & Command & Drawer & Pick-place & Microwave \\\\\n"
                     "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    (ROOT / "results" / "paper_tables.md").write_text("\n".join(md) + "\n")
    for k, v in tex.items():
        (ROOT / "paper" / "tables" / f"{k}.tex").write_text(v)
    print("\n".join(md[:20]))


if __name__ == "__main__":
    main()
